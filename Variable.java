public class Variable {
    public static void main(String[] args) {

        // 1. int (Integer) - Stores whole numbers
        int age = 21;

        // 2. double - Stores fractional/decimal numbers (Removed 'public' here)
        double gpa = 3.85;

        // 3. boolean - Stores true or false values
        boolean isStudent = true;

        // 4. char (Character) - Stores a single character
        char grade = 'A';

        // 5. String - Stores a sequence of text
        String name = "Alex";

        // --- Printing the values ---
        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("GPA: " + gpa);
        System.out.println("Grade: " + grade);
        System.out.println("Is a student? " + isStudent);
    }
}